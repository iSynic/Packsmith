static QByteArray romanName(const QString &name) {
    QByteArray result;
    for (QChar character : name) {
        int value = 0;
        while (value < 256 && classicRoman[value] != character.unicode()) ++value;
        if (value == 256) return {};
        result += char(value);
    }
    return result;
}
static QByteArray hfsKey(const QByteArray &name) {
    QByteArray key;
    for (uchar c : name) key += char(classicWeights[c]);
    return key;
}
static quint16 classicCrc(const QByteArray &data) {
    quint16 crc = 0;
    for (uchar c : data) {
        crc ^= quint16(c) << 8;
        for (int i=0;i<8;++i) crc = (crc << 1) ^ ((crc & 0x8000) ? 0x1021 : 0);
    }
    return crc;
}
static QByteArray classicHeader(const QByteArray &name, quint32 data, quint32 resource,
                                const QByteArray &finder, quint32 created, quint32 modified) {
    if (name.isEmpty() || name.size()>31 || name.contains(':') || name.contains(char(0)) || (!finder.isEmpty() && finder.size()!=32))
        throw std::runtime_error("Invalid classic export metadata");
    QByteArray header(128,0);
    header[1] = char(name.size()); memcpy(header.data()+2,name.constData(),name.size());
    if (finder.size()==32) {
        memcpy(header.data()+65,finder.constData(),8);
        // Preserve file properties and label color; Finder manages initialization,
        // desktop state, icon positions and containing-folder identifiers.
        header[73]=char(uchar(finder[8]) & 0xfc); header[101]=char(uchar(finder[9]) & 0x0e);
    }
    qToBigEndian<quint32>(data,header.data()+83); qToBigEndian<quint32>(resource,header.data()+87);
    qToBigEndian<quint32>(created,header.data()+91); qToBigEndian<quint32>(modified,header.data()+95);
    header[122]=char(129);header[123]=char(129);
    qToBigEndian<quint16>(classicCrc(header.left(124)),header.data()+124);
    return header;
}
